"""Project domain types and constants."""

import re
from dataclasses import dataclass
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator

from shared.domain.inputs import empty_to_none
from shared.domain.settings import Settings
from shared.keys import FALLBACK_PROJECT_ID

PROJECT_ID_MIN_LENGTH = 4
PROJECT_ID_MAX_LENGTH = 16
FORBIDDEN_PROJECT_ID_CHARACTERS_REGEX = r"[^A-Z0-9]"
# exempt from the project id rules
SPECIAL_PROJECT_IDS = [FALLBACK_PROJECT_ID]


class ProjectStatus:
    """Status of project."""

    ACTIVE = "active"
    INACTIVE = "inactive"
    DELETED = "deleted"


@dataclass(frozen=True)
class Project:
    """A project that raw files are assigned to. Datetimes are UTC-aware."""

    id: str
    name: str
    description: str | None
    status: str
    owner_email: str | None
    created_at_: datetime


@dataclass(frozen=True)
class ProjectSettings:
    """The assignment of settings to a project, with the scopes and filters it applies to. Datetimes are UTC-aware."""

    # generated by the database, only ever passed back to it
    id: str
    project_id: str
    settings: Settings
    # "*", a vendor name or an instrument ID; an assignment applies if any scope matches and no excluded one does
    scopes: list[str]
    excluded_scopes: list[str]
    # substrings of the raw file ID; include = any matches (empty = all), exclude = none matches
    raw_file_id_filter: list[str]
    raw_file_id_exclude_filter: list[str]
    created_at_: datetime


class NewProject(BaseModel):
    """A project to add, cf. `Project`. Strings are stripped."""

    model_config = ConfigDict(frozen=True, str_strip_whitespace=True)

    project_id: str
    name: str = Field(min_length=1, max_length=64)
    description: str | None = Field(default=None, max_length=256)
    owner_email: str | None = None

    _empty_to_none = field_validator("description", "owner_email", mode="before")(
        empty_to_none
    )

    @field_validator("project_id")
    @classmethod
    def _valid_project_id(cls, value: str) -> str:
        if value not in SPECIAL_PROJECT_IDS and (
            not PROJECT_ID_MIN_LENGTH <= len(value) <= PROJECT_ID_MAX_LENGTH
            or value.isdigit()
            or re.search(FORBIDDEN_PROJECT_ID_CHARACTERS_REGEX, value)
        ):
            raise ValueError(
                f"Invalid project id '{value}'. Please choose a different one."
            )
        return value
